// DTCG tokens (tokens/**/*.tokens.json) -> Sass maps consumed by src/themes and src/quasar.variables.scss.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import StyleDictionary from 'style-dictionary'

const ROOT = fileURLToPath(new URL('../', import.meta.url))
const OUT = 'src/tokens/generated/'
const LITERAL = /^(-?\d*\.?\d+(px|rem|em|ms|s|%)?|#[0-9a-f]{3,8}|(rgba?|hsla?|oklch)\([^()]*\)|-?[a-z][a-z-]*)$/i

const key = (name) => (/^\d+$/.test(name) ? name : `'${name}'`)
const family = (name) => (/^(-?[a-z][a-z-]*|[A-Za-z]+)$/.test(name) ? name : `'${name}'`)

function sassValue(token, names) {
  const value = token.original.$value
  const ref = typeof value === 'string' && value.match(/^\{([^}]+)\}$/)
  if (ref) {
    const [head, ...path] = ref[1].split('.')
    if (!names.has(head)) throw new Error(`${token.path.join('.')}: reference ${value} leaves this Sass module`)
    return `map.get($${head}, ${path.map(key).join(', ')})`
  }
  if (token.$type === 'fontFamily') return `(${[value].flat().map(family).join(', ')})`
  if (token.$type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`
  if (typeof value === 'number') return String(value)
  return LITERAL.test(value) ? value : `'${value}'`
}

function print(node, names, indent) {
  if (node.token) return sassValue(node.token, names)
  const pad = '  '.repeat(indent + 1)
  const entries = [...node.children].map(([name, child]) => `${pad}${key(name)}: ${print(child, names, indent + 1)},`)
  return `(\n${entries.join('\n')}\n${'  '.repeat(indent)})`
}

StyleDictionary.registerFormat({
  name: 'qds/sass-maps',
  format: ({ dictionary, options }) => {
    const root = { children: new Map() }
    for (const token of dictionary.allTokens) {
      let node = root
      for (const name of token.path.slice(options.strip ?? 0)) {
        if (!node.children.has(name)) node.children.set(name, { children: new Map() })
        node = node.children.get(name)
      }
      node.token = token
    }
    const names = new Set()
    const body = [...root.children].map(([name, node]) => {
      const line = `$${name}: ${print(node, names, 0)}${options.defaults ? ' !default' : ''};`
      names.add(name)
      return line
    })
    return `// Generated by scripts/build-tokens.mjs from tokens/**/*.tokens.json; do not edit.\n@use 'sass:map';\n\n${body.join('\n\n')}\n`
  },
})

const sd = new StyleDictionary({
  source: ['tokens/base.tokens.json', 'tokens/scheme.tokens.json', 'tokens/variants/*.tokens.json'],
  log: { verbosity: 'silent' },
  platforms: {
    scss: {
      buildPath: OUT,
      files: [
        { destination: '_default.scss', format: 'qds/sass-maps', filter: (t) => t.path[0] !== 'shadcn', options: { defaults: true } },
        { destination: '_shadcn.scss', format: 'qds/sass-maps', filter: (t) => t.path[0] === 'shadcn', options: { strip: 1 } },
      ],
    },
  },
})

const check = process.argv.includes('--check')
const stale = []
for (const { output, destination } of await sd.formatPlatform('scss')) {
  const path = `${ROOT}${destination}`
  let current = null
  try { current = readFileSync(path, 'utf8') } catch {}
  if (current === output) continue
  if (check) stale.push(destination)
  else writeFileSync(path, output)
}
if (stale.length) {
  console.error(`Generated token files are stale: ${stale.join(', ')}. Run pnpm tokens.`)
  process.exit(1)
}
